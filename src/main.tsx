import {AndroidAuthCallback} from "./AndroidAuthCallback";
import React from "react";
import { createRoot } from "react-dom/client";
import App from "./App";
import {AndroidUpdate} from "./AndroidUpdate";
import Admin from "./Admin";
import Support from "./Support";
import NotFound from "./NotFound";
import "./styles.css";
const redirected = new URLSearchParams(window.location.search).get("mingle_route");
if(redirected && redirected.startsWith("/") && !redirected.startsWith("//")) window.history.replaceState(null,"",redirected);
const path = window.location.pathname.replace(/\/$/,"") || "/";
const is404 = path === "/404" || !["/","/help","/admin","/admin/support"].includes(path);
if(is404 && path!=="/404") window.history.replaceState(null,"","/404");
if(is404) document.title="404 — Pagina niet gevonden | Mingle";
const root = document.getElementById("root");
if (root) createRoot(root).render(<React.StrictMode>{path==="/admin/support"?<Support admin/>:path==="/help"?<Support/>:path==="/admin"?<Admin/>:is404?<NotFound/>:<App/>}<AndroidUpdate/><AndroidAuthCallback/></React.StrictMode>);
